/**
 * 우클릭·휠클릭은 **화면 이동(팬)**이다 — 커서 아래 무엇이 있어도.
 *
 * 배경 핸들러(`onBackgroundPointerDown`)는 원래부터 `button === 1 || 2`를 팬으로
 * 처리하고, 컨텍스트 메뉴 쪽도 "움직인 우클릭 드래그는 메뉴를 열지 않는다"를
 * 전제로 짜여 있었다. 그런데 객체(노드·메모·선·영역)의 `pointerdown` 핸들러들이
 * 버튼을 보지 않고 먼저 `stopPropagation()`으로 가로채, 객체 위에서 우클릭 드래그를
 * 하면 화면이 아니라 **그 객체가 끌려다녔다**(제보).
 *
 * 그래서 객체 쪽 핸들러는 이 버튼일 때 **아무것도 하지 않고 그대로 흘려보낸다** —
 * `stopPropagation`을 부르지 않으므로 이벤트가 배경까지 올라가 팬이 시작된다.
 * 우클릭을 **누르고 떼기만** 한 경우는 종전대로 컨텍스트 메뉴가 뜬다(메뉴는
 * `openCtxAt`이 자체 히트테스트로 대상을 찾으므로 이 변경과 무관하다).
 *
 * 터치는 항상 `button === 0`이라 영향이 없고, 펜의 배럴 버튼(2)은 팬으로 취급한다.
 */
export function isPanButton(e: { button: number }): boolean {
  return e.button === 1 || e.button === 2;
}
