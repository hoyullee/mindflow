// 멘션 허브의 날짜 후보 — 스펙 표의 각 줄을 한 항목씩 덮는다.
//
// `today`는 **언제나 고정값**이다. 이 저장소는 시계를 읽는 테스트로 CI가 여러 번
// 깨졌다(자정 직후에 '오늘'이 어제가 되고, 달의 며칠에 돌리느냐로 구간 길이가
// 달라졌다). 그래서 이 파일에는 `new Date()`가 없다 — 기준 날짜는 전부 인자로 준다.
//
// 고정값으로 고른 날들:
//   2026-08-25(화) — 평범한 주 가운데. 이번 주 토요일=08-29, 다음 주 월요일=08-31.
//   2026-09-25(금) — "오늘이 그 요일일 때"의 경계.
//   2026-12-31(목) — 해를 넘기는 경계.

import { describe, expect, it } from 'vitest';
import { dateHits, wantsCalendarRow } from './noteDateQuery';

/** 검사하기 좋게 `iso`만 뽑는다. */
const isos = (q: string, today: string): string[] => dateHits(q, today).map((h) => h.iso);

const TUE = '2026-08-25'; // 화요일
const FRI = '2026-09-25'; // 금요일
const SAT = '2026-08-29'; // 토요일

describe('빈 검색어', () => {
  it('오늘·내일 둘만 낸다', () => {
    expect(dateHits('', TUE)).toEqual([
      { iso: '2026-08-25', label: '오늘', sub: '8.25 화' },
      { iso: '2026-08-26', label: '내일', sub: '8.26 수' },
    ]);
  });

  it('공백만 친 것도 빈 검색어다', () => {
    expect(isos('   ', TUE)).toEqual(['2026-08-25', '2026-08-26']);
  });
});

describe('이름 일부', () => {
  it('`오늘`·`내일`·`모레`는 그 날 하나씩', () => {
    expect(isos('오늘', TUE)).toEqual(['2026-08-25']);
    expect(isos('내일', TUE)).toEqual(['2026-08-26']);
    expect(isos('모레', TUE)).toEqual(['2026-08-27']);
  });

  it('`내`처럼 앞 글자만 쳐도 걸린다', () => {
    expect(isos('내', TUE)).toEqual(['2026-08-26']);
  });

  it('`토요일`은 이번 주 토요일 — 이름표도 그 이름이다', () => {
    expect(dateHits('토요일', TUE)).toEqual([{ iso: '2026-08-29', label: '이번 주 토요일', sub: '8.29 토' }]);
  });

  it('`다음주`는 기본 후보의 다음 주 월요일을 집는다', () => {
    expect(isos('다음주', TUE)).toEqual(['2026-08-31']);
  });

  it('아무 이름도 아니면 빈 목록', () => {
    expect(dateHits('ㅁㄴㅇㄹ', TUE)).toEqual([]);
  });
});

describe('일(day)만 — `27` · `27일`', () => {
  it('이번 달 27일과 다음 달 27일', () => {
    expect(dateHits('27', TUE)).toEqual([
      { iso: '2026-08-27', label: '모레', sub: '8.27 목' },
      { iso: '2026-09-27', label: '9월 27일', sub: '9.27 일' },
    ]);
  });

  it('`27일`도 같게 읽는다', () => {
    expect(isos('27일', TUE)).toEqual(['2026-08-27', '2026-09-27']);
  });

  it('이번 달 것이 이미 지났어도 넣는다 — 다만 다음 달 것이 뒤에 온다', () => {
    // 2026-09-28(월) 기준 — 27일은 어제다.
    expect(dateHits('27', '2026-09-28')).toEqual([
      { iso: '2026-09-27', label: '어제', sub: '9.27 일' },
      { iso: '2026-10-27', label: '10월 27일', sub: '10.27 화' },
    ]);
  });

  it('그 달에 없는 날은 조용히 빠진다 — 9월 31일', () => {
    expect(isos('31', FRI)).toEqual(['2026-10-31']);
  });
});

describe('월/일 — `8.27` 꼴', () => {
  it('구분 기호가 무엇이든 같은 날 하나', () => {
    for (const q of ['8.27', '8/27', '8-27', '8월27일', '8월 27일', '0827']) {
      expect(dateHits(q, TUE)).toEqual([{ iso: '2026-08-27', label: '모레', sub: '8.27 목' }]);
    }
  });

  it('올해 것이 이미 지났으면 내년으로 — 가장 가까운 그 월/일', () => {
    expect(isos('8.27', FRI)).toEqual(['2027-08-27']);
  });

  it('없는 날짜는 후보가 아니다 — 2월 30일', () => {
    expect(dateHits('2.30', TUE)).toEqual([]);
  });

  it('윤년에만 있는 2월 29일은 있는 해까지 넘어간다', () => {
    // 2026·2027은 평년이라 2028년이 가장 가까운 2월 29일이다.
    expect(isos('2.29', '2026-03-01')).toEqual(['2028-02-29']);
  });

  it('해를 넘기는 경계 — 12월 31일에 친 `1.5`는 내년 1월 5일', () => {
    // 이름표가 `1월 5일`인 것은 **숫자로 찾았기 때문**이다(아래 「이름표는 친 말과 이어진다」).
    expect(dateHits('1.5', '2026-12-31')).toEqual([{ iso: '2027-01-05', label: '1월 5일', sub: '1.5 화' }]);
  });
});

describe('달만 — `9월` · `9.`', () => {
  it('그 달 1~3일', () => {
    expect(isos('9월', TUE)).toEqual(['2026-09-01', '2026-09-02', '2026-09-03']);
    expect(isos('9.', TUE)).toEqual(['2026-09-01', '2026-09-02', '2026-09-03']);
  });

  it('이번 달이면 1일이 아니라 오늘부터 사흘', () => {
    expect(isos('9월', FRI)).toEqual(['2026-09-25', '2026-09-26', '2026-09-27']);
  });

  it('달 끝에서는 거기서 끊는다 — 다음 달로 새지 않는다', () => {
    expect(isos('9월', '2026-09-29')).toEqual(['2026-09-29', '2026-09-30']);
  });

  it('지난 달 이름은 내년 그 달로 읽는다', () => {
    expect(isos('3월', FRI)).toEqual(['2027-03-01', '2027-03-02', '2027-03-03']);
  });
});

describe('요일 — 다가오는 그 날', () => {
  it('`금`·`금요일` 모두 다가오는 금요일', () => {
    expect(dateHits('금', TUE)).toEqual([{ iso: '2026-08-28', label: '이번 주 금요일', sub: '8.28 금' }]);
    expect(isos('금요일', TUE)).toEqual(['2026-08-28']);
  });

  it('오늘이 금요일이면 오늘이 아니라 다음 주 금요일', () => {
    expect(dateHits('금', FRI)).toEqual([{ iso: '2026-10-02', label: '다음 주 금요일', sub: '10.2 금' }]);
  });

  it('`다음주금요일`·`다음주 금`은 이번 주가 끝난 뒤의 금요일', () => {
    expect(dateHits('다음주금요일', TUE)).toEqual([{ iso: '2026-09-04', label: '다음 주 금요일', sub: '9.4 금' }]);
    expect(isos('다음주 금', TUE)).toEqual(['2026-09-04']);
  });
});

describe('겹치는 날짜는 하나로', () => {
  it('이름 규칙과 요일 규칙이 같은 날이면 한 줄 — 먼저 나온 이름표를 남긴다', () => {
    // 2026-08-27(목)의 모레 = 08-29(토) = 이번 주 토요일. `토`는 둘 다에 걸린다.
    expect(dateHits('토', '2026-08-27')).toEqual([{ iso: '2026-08-29', label: '모레', sub: '8.29 토' }]);
  });

  it('다른 날이면 둘 다 — 오늘이 토요일일 때 `토요일`', () => {
    // 기본 후보의 `이번 주 토요일`은 오늘이고, 요일 규칙은 다음 주로 민다.
    expect(dateHits('토요일', SAT)).toEqual([
      { iso: '2026-08-29', label: '오늘', sub: '8.29 토' },
      { iso: '2026-09-05', label: '다음 주 토요일', sub: '9.5 토' },
    ]);
  });
});

describe('달력 행(`다른 날짜 고르기…`)', () => {
  it('검색어가 비었으면 붙인다', () => {
    expect(wantsCalendarRow('')).toBe(true);
    expect(wantsCalendarRow('  ')).toBe(true);
  });

  it('숫자가 섞였으면 붙인다 — 우리가 못 푸는 날짜일 수 있다', () => {
    expect(wantsCalendarRow('27')).toBe(true);
    expect(wantsCalendarRow('8.27')).toBe(true);
  });

  it('`날`·`달`이 들어가도 붙인다', () => {
    expect(wantsCalendarRow('날짜')).toBe(true);
    expect(wantsCalendarRow('다음 달')).toBe(true);
  });

  it('이름만 친 경우는 붙이지 않는다', () => {
    expect(wantsCalendarRow('금요일')).toBe(false);
    expect(wantsCalendarRow('오늘')).toBe(false);
  });
});

describe('이름표는 **친 말과 이어진다** — 숫자로 찾은 날에는 요일 이름표를 붙이지 않는다', () => {
  it('`9월`은 `9월 1일`이지 `다음 주 화요일`이 아니다', () => {
    // 사람은 자기가 친 말이 되돌아오길 기대한다. 요일 이름표는 이름으로 찾았을
    // 때만 답이 된다(고치기 전에는 `다음 주 화요일`이 나왔다).
    expect(dateHits('9월', '2026-08-25').map((h) => h.label)).toEqual(['9월 1일', '9월 2일', '9월 3일']);
  });

  it('이름으로 찾으면 요일 이름표가 그대로 나온다', () => {
    expect(dateHits('금요일', '2026-08-25')[0]?.label).toBe('이번 주 금요일');
    expect(dateHits('다음주 금', '2026-08-25')[0]?.label).toBe('다음 주 금요일');
  });

  it('오늘·내일·모레·어제는 **어느 쪽에서 찾아도** 그대로다 — 짧고 분명해서', () => {
    expect(dateHits('8.27', '2026-08-25')[0]?.label).toBe('모레');
    expect(dateHits('모레', '2026-08-25')[0]?.label).toBe('모레');
  });
});
